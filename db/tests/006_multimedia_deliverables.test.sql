-- Schema tests for generated media (spec 017). Rolled back by scripts/db.mjs.

create function pg_temp.assert_true(condition boolean, label text)
returns void
language plpgsql
as $$
begin
  if condition is not true then
    raise exception 'assertion failed: %', label;
  end if;
end;
$$;

select pg_temp.assert_true(
  (select data_type from information_schema.columns
   where table_schema = 'public' and table_name = 'messages'
     and column_name = 'media') = 'jsonb',
  'messages.media is jsonb'
);
select pg_temp.assert_true(
  (select count(*) from information_schema.columns
   where table_schema = 'public' and table_name = 'generated_media'
     and column_name in (
       'id', 'user_id', 'conversation_id', 'message_id', 'kind', 'status',
       'mime_type', 'file_name', 'byte_size', 'content', 'width', 'height',
       'duration_seconds', 'model_id', 'model_version', 'provider_prompt', 'parameters',
       'citation', 'error_code', 'error_message', 'estimated_cost_usd', 'latency_ms',
       'attempts', 'created_at', 'updated_at'
     )) = 25,
  'generated_media columns exist'
);
select pg_temp.assert_true(
  (select count(*) from pg_constraint
   where conrelid = 'public.generated_media'::regclass
     and conname in (
       'generated_media_kind_check', 'generated_media_status_check',
       'generated_media_byte_size_check', 'generated_media_duration_check',
       'generated_media_ready_check', 'generated_media_attempts_check'
     )) = 6,
  'generated_media constraints exist'
);
select pg_temp.assert_true(
  exists (
    select 1 from pg_indexes
    where schemaname = 'public'
      and indexname = 'generated_media_user_created_idx'
  ),
  'user/created_at index exists'
);

do $$
declare
  v_user uuid;
  v_conversation uuid;
  v_message uuid;
  v_media uuid;
begin
  insert into public.users (first_name, last_name, email, password_hash)
  values ('Media', 'Deliverable', 'media.deliverable@example.com', 'seed-password-hash-with-32-chars')
  returning id into v_user;

  insert into public.conversations (user_id, expert_id)
  values (v_user, 'cmo')
  returning id into v_conversation;

  -- Legacy insert keeps the new optional column null.
  insert into public.messages (conversation_id, role, content)
  values (v_conversation, 'expert', 'Legacy answer')
  returning id into v_message;

  if exists (
    select 1 from public.messages where id = v_message and media is not null
  ) then
    raise exception 'assertion failed: legacy message was changed';
  end if;

  insert into public.generated_media
    (user_id, conversation_id, message_id, kind, status, mime_type, file_name,
     byte_size, content, width, height, model_id, provider_prompt, parameters, attempts)
  values
    (v_user, v_conversation, v_message, 'image', 'ready', 'image/png',
     'image.png', 8, convert_to('fake-png', 'UTF8'), 1024, 1024, 'gpt-image-2',
     'Create a square image for the test',
     jsonb_build_object('kind', 'image', 'size', '1024x1024'), 1)
  returning id into v_media;

  update public.messages
     set media = jsonb_build_object(
       'mediaId', v_media::text,
       'kind', 'image',
       'status', 'ready'
     )
   where id = v_message;

  perform pg_temp.assert_true(
    (select media ->> 'mediaId' from public.messages where id = v_message)
      = v_media::text,
    'message references the generated media id'
  );

  perform pg_temp.assert_true(
    (select length(content) from public.generated_media where id = v_media) = 8,
    'generated bytes round-trip'
  );

  begin
    insert into public.generated_media
      (user_id, kind, status, file_name, model_id, provider_prompt, parameters)
    values (v_user, 'image', 'invented', 'bad.png', 'gpt-image-2', 'test', '{}'::jsonb);
    raise exception 'assertion failed: invalid status was allowed';
  exception when check_violation then
    null;
  end;

  begin
    insert into public.generated_media
      (user_id, kind, status, file_name, byte_size, model_id, provider_prompt, parameters)
    values (v_user, 'video', 'ready', 'big.mp4', 20971521, 'gemini', 'test', '{}'::jsonb);
    raise exception 'assertion failed: oversized file was allowed';
  exception when check_violation then
    null;
  end;

  begin
    insert into public.generated_media
      (user_id, kind, status, file_name, model_id, provider_prompt, parameters, duration_seconds)
    values (v_user, 'video', 'queued', 'long.mp4', 'gemini', 'test', '{}'::jsonb, 20);
    raise exception 'assertion failed: duration above 8 seconds was allowed';
  exception when check_violation then
    null;
  end;

  -- Deleting the message cascades the bytes, matching chat retention.
  delete from public.messages where id = v_message;

  if exists (select 1 from public.generated_media where id = v_media) then
    raise exception 'assertion failed: generated media did not cascade';
  end if;

  delete from public.users where id = v_user;
end $$;
